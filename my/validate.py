# -*- coding: utf-8 -*-
"""
Umbeck理论验证脚本
- 功能：分析基线场景的数据，生成三张图表，分别对应Umbeck论文的三个核心发现，
        从而验证LLM智能体能够复现经典经济学理论中的人类社会行为。
- 输入：基线实验组的 round_metrics_enhanced.csv 和 ownership_timeseries.csv 文件。
- 输出：三张核心验证图表。
"""

import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import os
import re
import numpy as np

# --- 1. 参数设置 ---

# 设定哪个实验组是我们的“基线情境”
BASELINE_GROUP_DIR = "100"
BASELINE_GROUP_LABEL = "10 Agents, 80 Plots (Baseline)"

# 基础路径
BASE_PATH = "D:/yulan-onesim/YuLan-OneSim/my/"

# 输入文件名
ROUND_METRICS_FILENAME = "round_metrics_enhanced.csv"
OWNERSHIP_FILENAME = "ownership_timeseries.csv"

# 输出图表的目录
OUTPUT_DIR = os.path.join(BASE_PATH, "umbeck_validation_figures_8")

# 平滑窗口
SMOOTHING_WINDOW = 5

# --- 2. 主流程 ---

def validate_umbeck_findings():
    """主函数，生成三张核心验证图表"""

    # 创建输出目录
    if not os.path.exists(OUTPUT_DIR):
        os.makedirs(OUTPUT_DIR)

    # --- 数据加载 ---
    round_metrics_path = os.path.join(BASE_PATH, BASELINE_GROUP_DIR, ROUND_METRICS_FILENAME)
    ownership_path = os.path.join(BASE_PATH, BASELINE_GROUP_DIR, OWNERSHIP_FILENAME)

    if not os.path.exists(round_metrics_path) or not os.path.exists(ownership_path):
        print("[ERROR] Required baseline data files not found. Please check paths.")
        return

    df_rounds = pd.read_csv(round_metrics_path)
    df_ownership = pd.read_csv(ownership_path)

    print(f"[INFO] Successfully loaded data for baseline group: '{BASELINE_GROUP_LABEL}'")

    # --- 证据 1: 约束的本质 - 冲突与威慑的演化 ---
    # **修正部分开始**
    # 我们直接使用CSV中已有的 'raid_ratio' 和 'defend_ratio' 列
    # 这两列已经代表了智能体在攻击和防御上的策略倾向
    
    fig1, ax1 = plt.subplots(figsize=(12, 7))
    
    # 检查列是否存在
    if 'raid_ratio' not in df_rounds.columns or 'defend_ratio' not in df_rounds.columns:
        print("[ERROR] 'raid_ratio' or 'defend_ratio' not found in round_metrics_enhanced.csv.")
        print("Please ensure you are using the correct CSV file generated by analysis_advance.py.")
        return

    # 绘制冲突行为占比（raid_ratio）
    raid_ratio_smooth = df_rounds['raid_ratio'].rolling(window=SMOOTHING_WINDOW, min_periods=1).mean()
    ax1.plot(df_rounds['round'], raid_ratio_smooth, color='red', label='Aggressive Behavior (Raid Ratio)', linewidth=2.5)
    
    # 绘制防御行为占比（defend_ratio）
    defend_ratio_smooth = df_rounds['defend_ratio'].rolling(window=SMOOTHING_WINDOW, min_periods=1).mean()
    ax1.plot(df_rounds['round'], defend_ratio_smooth, color='blue', label='Defensive Behavior (Defend Ratio)', linewidth=2.5)
    
    # **修正部分结束**

    ax1.set_title('Evidence 1: The Evolution of Conflict and Deterrence', fontsize=18, pad=20)
    ax1.set_xlabel('Round', fontsize=14)
    ax1.set_ylabel('Proportion of Total Stamina', fontsize=14)
    ax1.legend(fontsize=12)
    ax1.set_xlim(0, df_rounds['round'].max())
    
    output_path1 = os.path.join(OUTPUT_DIR, 'fig_umbeck_1_conflict_evolution.png')
    plt.tight_layout()
    plt.savefig(output_path1, dpi=150)
    plt.close()
    print(f"[SUCCESS] Saved Chart 1 (Conflict & Deterrence) to: {output_path1}")


    # --- 证据 2: 同质土地的均分结论 - Gini系数 ---
    fig2, ax2 = plt.subplots(figsize=(12, 7))

    # 从ownership数据计算Gini系数
    agent_cols = [col for col in df_ownership.columns if 'agent' in col]
    if not agent_cols:
        print("[ERROR] No agent columns found in ownership_timeseries.csv. Cannot calculate Gini.")
        return

    gini_per_round = df_ownership.apply(lambda row: gini(row[agent_cols]), axis=1)

    ax2.plot(df_ownership['round'], gini_per_round.rolling(window=SMOOTHING_WINDOW, min_periods=1).mean(), color='green', linewidth=2.5)

    ax2.set_title('Evidence 2: Convergence to Equal Distribution (Gini Coefficient of Land)', fontsize=18, pad=20)
    ax2.set_xlabel('Round', fontsize=14)
    ax2.set_ylabel('Gini Coefficient (0 = Perfect Equality)', fontsize=14)
    ax2.axhline(y=0.1, color='grey', linestyle='--', label='High Equality Threshold (Gini=0.1)')
    ax2.legend()
    ax2.set_xlim(0, df_ownership['round'].max())
    ax2.set_ylim(0, max(0.5, gini_per_round.max() * 1.1))

    output_path2 = os.path.join(OUTPUT_DIR, 'fig_umbeck_2_gini_of_land.png')
    plt.tight_layout()
    plt.savefig(output_path2, dpi=150)
    plt.close()
    print(f"[SUCCESS] Saved Chart 2 (Gini of Land) to: {output_path2}")

    # --- 证据 3: 同质土地的均分结论 - 份额时序图 ---
    fig3, ax3 = plt.subplots(figsize=(12, 7))

    for agent_col in agent_cols:
        ax3.plot(df_ownership['round'], df_ownership[agent_col], alpha=0.6)

    # 绘制理论均值线
    # 动态计算总地块数
    total_plots = sum(df_ownership.iloc[0][agent_cols]) if not df_ownership.empty else 100
    num_agents = len(agent_cols)
    mean_plots = total_plots / num_agents if num_agents > 0 else 0
    
    ax3.axhline(y=mean_plots, color='black', linestyle='--', linewidth=2, label=f'Theoretical Mean ({mean_plots:.1f} plots)')

    ax3.set_title('Evidence 3: Stabilization of Individual Property Shares', fontsize=18, pad=20)
    ax3.set_xlabel('Round', fontsize=14)
    ax3.set_ylabel('Number of Plots Owned per Agent', fontsize=14)
    ax3.legend()
    ax3.set_xlim(0, df_ownership['round'].max())

    output_path3 = os.path.join(OUTPUT_DIR, 'fig_umbeck_3_ownership_shares.png')
    plt.tight_layout()
    plt.savefig(output_path3, dpi=150)
    plt.close()
    print(f"[SUCCESS] Saved Chart 3 (Ownership Shares) to: {output_path3}")

def gini(values):
    """计算基尼系数的辅助函数"""
    if np.sum(values) == 0:
        return 0
    values = np.asarray(values, dtype=float)
    values = np.sort(values)
    n = len(values)
    index = np.arange(1, n + 1)
    return (np.sum((2 * index - n - 1) * values)) / (n * np.sum(values))


if __name__ == '__main__':
    validate_umbeck_findings()